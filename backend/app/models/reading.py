from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from ..db.base import Base, JSONType, UUIDPk, utcnow


class ReadingProgress(UUIDPk, Base):
    __tablename__ = "reading_progress"
    __table_args__ = (UniqueConstraint("user_id", "source_id", "manga_id", "chapter_id", name="uq_progress_chapter"),)

    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    source_id: Mapped[str] = mapped_column(String(64))
    manga_id: Mapped[str] = mapped_column(String(512), index=True)
    chapter_id: Mapped[str] = mapped_column(String(1024))
    chapter_number: Mapped[float | None] = mapped_column(Float)
    chapter_title: Mapped[str] = mapped_column(String(512), default="")
    page_index: Mapped[int] = mapped_column(Integer, default=0)
    page_count: Mapped[int] = mapped_column(Integer, default=0)
    completed: Mapped[bool] = mapped_column(Boolean, default=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)
    server_updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, index=True)


class HistoryEntry(Base):
    """A reading session. Id is generated by the client so uploads are idempotent."""

    __tablename__ = "history_entries"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    source_id: Mapped[str] = mapped_column(String(64))
    manga_id: Mapped[str] = mapped_column(String(512))
    manga_title: Mapped[str] = mapped_column(String(512), default="")
    cover_url: Mapped[str] = mapped_column(String(2048), default="")
    chapter_id: Mapped[str] = mapped_column(String(1024))
    chapter_title: Mapped[str] = mapped_column(String(512), default="")
    chapter_number: Mapped[float | None] = mapped_column(Float)
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    read_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)
    duration_seconds: Mapped[int] = mapped_column(Integer, default=0)
    pages_read: Mapped[int] = mapped_column(Integer, default=0)
    server_updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class SearchHistory(Base):
    __tablename__ = "search_history"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    query: Mapped[str] = mapped_column(String(256))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)


class DeviceDownload(UUIDPk, Base):
    """Registry of chapters downloaded on each device (lets other devices show
    what is available offline where, and restores the list after reinstall)."""

    __tablename__ = "device_downloads"
    __table_args__ = (UniqueConstraint("user_id", "device_id", "source_id", "chapter_id", name="uq_download"),)

    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    device_id: Mapped[str] = mapped_column(String(128))
    source_id: Mapped[str] = mapped_column(String(64))
    manga_id: Mapped[str] = mapped_column(String(512))
    chapter_id: Mapped[str] = mapped_column(String(1024))
    manga_title: Mapped[str] = mapped_column(String(512), default="")
    chapter_title: Mapped[str] = mapped_column(String(512), default="")
    status: Mapped[str] = mapped_column(String(16), default="completed")
    page_count: Mapped[int] = mapped_column(Integer, default=0)
    size_bytes: Mapped[int] = mapped_column(Integer, default=0)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)


class TrackedTitle(Base):
    """Per (source, manga) state for the update checker, shared across users."""

    __tablename__ = "tracked_titles"

    source_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    manga_id: Mapped[str] = mapped_column(String(512), primary_key=True)
    known_chapter_ids: Mapped[list[str]] = mapped_column(JSONType, default=list)
    chapter_count: Mapped[int] = mapped_column(Integer, default=0)
    last_checked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_error: Mapped[str | None] = mapped_column(Text)


class ChapterUpdate(UUIDPk, Base):
    __tablename__ = "chapter_updates"
    __table_args__ = (UniqueConstraint("user_id", "source_id", "chapter_id", name="uq_update_chapter"),)

    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    source_id: Mapped[str] = mapped_column(String(64))
    manga_id: Mapped[str] = mapped_column(String(512))
    manga_title: Mapped[str] = mapped_column(String(512), default="")
    cover_url: Mapped[str] = mapped_column(String(2048), default="")
    chapter_id: Mapped[str] = mapped_column(String(1024))
    chapter_title: Mapped[str] = mapped_column(String(512), default="")
    chapter_number: Mapped[float | None] = mapped_column(Float)
    detected_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)
    seen: Mapped[bool] = mapped_column(Boolean, default=False)
    extra: Mapped[dict[str, Any]] = mapped_column(JSONType, default=dict)
